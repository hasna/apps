#!/usr/bin/env bun
// Emit the classic SDK API from the same JavaScript the package executes.
import ts from 'typescript';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const configPath = resolve(root, 'tsconfig.sdk-declarations.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root, undefined, configPath);
// Adjacent generated declarations must never mask the canonical JS on later runs.
const expected = ['client/http-store.d.mts', 'client/transport.d.mts', 'sdk/index.d.mts', 'sdk/types.d.ts'];
const generatedPaths = new Set(expected.map((file) => resolve(root, file)));
const host = ts.createCompilerHost(parsed.options);
const exists = host.fileExists.bind(host);
host.fileExists = (file) => !generatedPaths.has(resolve(file)) && exists(file);
const program = ts.createProgram(parsed.fileNames, parsed.options, host);
const outputs = new Map();
const result = program.emit(undefined, (file, text) => outputs.set(file, text));
const diagnostics = [config.error, ...parsed.errors, ...ts.getPreEmitDiagnostics(program), ...result.diagnostics].filter(Boolean);
if (diagnostics.length || result.emitSkipped) {
  console.error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (name) => name, getCurrentDirectory: () => root, getNewLine: () => '\n',
  }));
  process.exit(1);
}
const actual = [...outputs.keys()].map((file) => relative(resolve(root, '.sdk-types'), file)).sort();
if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error('Unexpected SDK declaration output inventory');
for (const [file, text] of outputs) {
  const destination = resolve(root, relative(resolve(root, '.sdk-types'), file));
  const generated = '// Generated by scripts/sdk-declarations.mjs; edit the canonical source instead.\n' + text;
  if (check) {
    if (readFileSync(destination, 'utf8') !== generated) throw new Error(`Stale declaration: ${relative(root, destination)}`);
  } else {
    mkdirSync(dirname(destination), { recursive: true });
    writeFileSync(destination, generated);
  }
}
console.log(`Classic SDK declarations ${check ? 'verified' : 'generated'}: ${outputs.size} files`);
