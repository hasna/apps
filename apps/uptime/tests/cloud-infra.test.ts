import { expect, test } from "bun:test";
import { readFileSync } from "node:fs";

function read(path: string): string {
  return readFileSync(path, "utf8");
}

test("Dockerfile builds a hosted non-root Bun runtime without plaintext secrets", () => {
  const dockerfile = read("Dockerfile");
  const packageDockerfile = read("Dockerfile.package");
  const dockerignore = read(".dockerignore");

  expect(dockerfile).toContain("FROM oven/bun:1.3.13-slim AS build");
  expect(dockerfile).toContain("bun run build");
  expect(dockerfile).toContain("HASNA_UPTIME_MODE=hosted");
  expect(dockerfile).toContain("--uid 10001");
  expect(dockerfile).toContain("USER uptime");
  expect(dockerfile).toContain("HEALTHCHECK");
  expect(packageDockerfile).toContain("FROM public.ecr.aws/docker/library/node:22-alpine@sha256:16e22a550f3863206a3f701448c45f7912c6896a62de43add43bb9c86130c3e2 AS bun");
  expect(packageDockerfile).toContain("FROM public.ecr.aws/docker/library/alpine:3.22@sha256:14358309a308569c32bdc37e2e0e9694be33a9d99e68afb0f5ff33cc1f695dce AS runtime");
  expect(packageDockerfile).toContain("npm install -g bun@1.3.13");
  expect(packageDockerfile).toContain("apk add --no-cache ca-certificates libgcc libstdc++");
  expect(packageDockerfile).toContain("COPY dist ./dist");
  expect(packageDockerfile).toContain("COPY package.json bun.lock ./");
  expect(packageDockerfile).toContain("bun install --production --frozen-lockfile");
  expect(dockerfile).toContain("/usr/local/bin/uptimemon");
  expect(dockerfile).toContain('exec bun /app/dist/cli/index.js "$@"');
  expect(packageDockerfile).toContain("/usr/local/bin/uptimemon");
  expect(packageDockerfile).toContain('exec bun /app/dist/cli/index.js "$@"');
  // Transition release: the retired `uptime` name keeps working via the shim.
  expect(dockerfile).toContain("/usr/local/bin/uptime");
  expect(dockerfile).toContain('exec bun /app/dist/cli/deprecated-uptime.js "$@"');
  expect(packageDockerfile).toContain("/usr/local/bin/uptime");
  expect(packageDockerfile).toContain('exec bun /app/dist/cli/deprecated-uptime.js "$@"');
  expect(packageDockerfile).toContain("-u 10001");
  expect(packageDockerfile).not.toContain("FROM oven/bun");
  expect(packageDockerfile).not.toContain("node:22-slim");
  expect(dockerignore).not.toMatch(/^dist$/m);
  expect(dockerfile).not.toContain("mkdir -p /data/uptime");
  expect(packageDockerfile).not.toContain("mkdir -p /data/uptime");
  expect(dockerfile).not.toContain("HASNA_UPTIME_HOSTED_TOKEN=");
  expect(dockerfile).not.toContain("DATABASE_URL=");
  expect(dockerfile).not.toContain("AWS_SECRET_ACCESS_KEY");
  expect(packageDockerfile).not.toContain("HASNA_UPTIME_HOSTED_TOKEN=");
  expect(packageDockerfile).not.toContain("DATABASE_URL=");
  expect(packageDockerfile).not.toContain("AWS_SECRET_ACCESS_KEY");
});

